// The README's tool list is generated from lib/tools.ts so the count and names can't drift.
// `npm run readme:tools` rewrites the block between the markers; tests/readme.test.ts fails CI
// when the README is out of date. Node 24 runs lib/tools.ts directly (built-in type stripping).

import { readFileSync, writeFileSync } from "fs";
import { join } from "path";
import { pathToFileURL } from "url";

export const START = "<!-- TOOLS:START — generated by `npm run readme:tools`, do not edit by hand -->";
export const END = "<!-- TOOLS:END -->";

/**
 * @param {{ name: string; category: string }[]} tools
 * @param {readonly string[]} categories
 * @returns {string}
 */
export function renderToolsSection(tools, categories) {
  const lines = [START, `## 🛠️ Tools (${tools.length} total)`, ""];
  for (const cat of categories) {
    const names = tools.filter((t) => t.category === cat).map((t) => t.name);
    if (!names.length) continue;
    lines.push(`### ${cat}`, names.join(" · "), "");
  }
  lines.push(END);
  return lines.join("\n");
}

/**
 * @param {string} readme
 * @param {string} section
 * @returns {string}
 */
export function replaceToolsSection(readme, section) {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error("README is missing the TOOLS markers");
  return readme.slice(0, start) + section + readme.slice(end + END.length);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const { tools, categories } = await import(pathToFileURL(join(process.cwd(), "lib", "tools.ts")).href);
  const file = join(process.cwd(), "README.md");
  const before = readFileSync(file, "utf8");
  const after = replaceToolsSection(before, renderToolsSection(tools, categories));
  writeFileSync(file, after);
  console.log(after === before ? "README tool list already up to date." : `README tool list updated (${tools.length} tools).`);
}
