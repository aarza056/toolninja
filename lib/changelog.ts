// links always come from the registry. Newest release first; add new releases at the top.

export type ChangeKind = "feature" | "new" | "improved" | "guide" | "fix";

export interface ChangeItem {
  kind: ChangeKind;
  /** Plain-language description. Optional for "new" (the tool's own description is used) and "guide". */
  text?: string;
  /** A tool this item is about. */
  tool?: string;
  /** Several tools shown as a compact list (e.g. the launch set). */
  tools?: string[];
  /** A blog guide this item is about. */
  post?: string;
  /** Link for site-level items. */
  href?: string;
}

export interface Release {
  date: string; // YYYY-MM-DD
  title: string;
  summary: string;
  items: ChangeItem[];
}

